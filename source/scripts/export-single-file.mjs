import {readFile,writeFile} from 'node:fs/promises';
import {dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
const source=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const dist=resolve(source,'dist');
let html=await readFile(resolve(dist,'index.html'),'utf8');
const script=html.match(/<script\b[^>]*\bsrc="([^"]+)"[^>]*><\/script>/);
const stylesheet=html.match(/<link\b[^>]*\bhref="([^"]+\.css)"[^>]*>/);
if(!script||!stylesheet)throw new Error('Expected one compiled script and stylesheet.');
const js=(await readFile(resolve(dist,script[1]),'utf8')).replaceAll('</script','<\\/script');
const css=(await readFile(resolve(dist,stylesheet[1]),'utf8')).replaceAll('</style','<\\/style');
html=html.replace(script[0],()=>'<script type="module">'+js+'</script>');
html=html.replace(stylesheet[0],()=>'<style>'+css+'</style>');
const icon=await readFile(resolve(dist,'favicon.svg'));
html=html.replace('./favicon.svg','data:image/svg+xml;base64,'+icon.toString('base64'));
const output=resolve(source,'..','index.html');
await writeFile(output,html);
console.log('Exported self-contained publish file:',output);
